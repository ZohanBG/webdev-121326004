-- Slice 2: a booking ties one student to one workstation in one block on one date.
-- `date` and `block` are the slot as people see it in Europe/Sofia. A block's start time is
-- computed from them by one helper in the service layer, never stored a second time.

CREATE TABLE bookings (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  workstation_id integer NOT NULL REFERENCES workstations (id) ON DELETE RESTRICT,
  date           date NOT NULL,
  block          smallint NOT NULL CHECK (block BETWEEN 1 AND 6),
  status         text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'cancelled')),
  created_at     timestamptz NOT NULL DEFAULT now(),
  cancelled_at   timestamptz,
  cancelled_by   integer REFERENCES users (id) ON DELETE RESTRICT,
  -- a cancelled booking always says when and by whom; an active one never does
  CONSTRAINT bookings_cancellation_recorded
    CHECK ((status = 'cancelled') = (cancelled_at IS NOT NULL AND cancelled_by IS NOT NULL))
);

-- One active booking per workstation per block (AC-3) and per student per block (AC-5), even when
-- two requests arrive at the same moment. The service tells the two apart by these names.
CREATE UNIQUE INDEX bookings_one_per_workstation ON bookings (workstation_id, date, block) WHERE status = 'active';
CREATE UNIQUE INDEX bookings_one_per_student ON bookings (user_id, date, block) WHERE status = 'active';

CREATE INDEX bookings_date ON bookings (date);
