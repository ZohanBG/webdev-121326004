-- The model feature: one row per request that reached the model, for the daily limit (10 per student
-- per day, midnight Europe/Sofia). The request text is never stored; only how the call ended.

CREATE TABLE suggestion_requests (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  outcome    text NOT NULL CHECK (outcome IN ('ok', 'timeout', '429', '529', 'truncated', 'invalid', 'error'))
);

CREATE INDEX suggestion_requests_user_time ON suggestion_requests (user_id, created_at);
