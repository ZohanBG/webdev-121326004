-- Failed sign-ins, so that 5 failures for one email from one address within 15 minutes lock that pair (AC-45).
-- The email is stored lower-cased and trimmed, whether or not an account has it; no password is stored.
CREATE TABLE sign_in_failures (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email     text NOT NULL,
  ip        text NOT NULL,
  failed_at timestamptz NOT NULL
);

CREATE INDEX sign_in_failures_email_ip_time ON sign_in_failures (email, ip, failed_at);
