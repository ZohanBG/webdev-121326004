-- Slice 1: who signs in, and the labs they see.
-- Foreign keys use ON DELETE RESTRICT: the app takes labs and workstations out of service,
-- it never deletes them, so booking history is never lost.

CREATE TABLE users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         text NOT NULL,
  -- NULL for an account that signs in only through Google, or whose password was cleared on linking
  password_hash text,
  role          text NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'staff')),
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_unique ON users (lower(email));

CREATE TABLE sessions (
  -- SHA-256 of the cookie value, so a copy of this table cannot be used to sign in
  id         text PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_user_id ON sessions (user_id);

CREATE TABLE labs (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL CHECK (length(trim(name)) > 0),
  room       text NOT NULL CHECK (length(trim(room)) > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE workstations (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id     integer NOT NULL REFERENCES labs (id) ON DELETE RESTRICT,
  label      text NOT NULL CHECK (length(trim(label)) > 0),
  features   text[] NOT NULL DEFAULT '{}'
             CHECK (features <@ ARRAY['quiet', 'dual-monitor', 'gpu']::text[]),
  in_service boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (lab_id, label)
);
CREATE INDEX workstations_lab_id ON workstations (lab_id);
