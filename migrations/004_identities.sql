-- Sign in with Google. One row in users per person; one row here per provider account linked to it.

CREATE TABLE identities (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  provider            text NOT NULL CHECK (provider IN ('google')),
  provider_account_id text NOT NULL,
  created_at          timestamptz NOT NULL DEFAULT now(),
  UNIQUE (provider, provider_account_id)
);
CREATE INDEX identities_user_id ON identities (user_id);

-- A sign-in with a provider that has started and not finished: the state sent to the provider (only its
-- SHA-256 is kept) and the PKCE verifier, which never leaves the server. Each row is used once, within 10 minutes.
CREATE TABLE oauth_attempts (
  state_hash    text PRIMARY KEY,
  code_verifier text NOT NULL,
  expires_at    timestamptz NOT NULL
);
